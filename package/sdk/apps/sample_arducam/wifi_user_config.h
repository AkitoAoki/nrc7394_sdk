//  ・SSID、IPアドレス設定方式、固定IPアドレス、ネットマスク、ゲートウェイを
//    本ファイルで定義する。
//  ・本サンプルでは、HaLowカメラ用途を想定し、固定IPアドレスで動作する。
//  ・NVS（不揮発性ストレージ）を使用することで、ビルド時定義ではなく
//    実行環境側から設定値を上書きする構成も可能である。
