#ifndef __WIFI_USER_CONFIG_H__
#define __WIFI_USER_CONFIG_H__

//======================================================
//  Wi-Fiユーザー設定概要
//======================================================
//  本ヘッダーファイルに定義した値は、SDK標準のWi-Fi設定よりも優先される。
//
//  標準設定値は、以下のSDK側ヘッダーファイルに定義されている。
//      wifi_common/wifi_config.h
//
//  また、NVS（non-volatile storage）を使用する場合は、
//  以下のSDK側ヘッダーファイルで定義されるキーにより、
//  実行時または保存済み設定として上書き可能である。
//      wifi_common/nvs_config.h
//
//  注意：
//  ・本ファイルの値はビルド時に固定されるため、装置ごとにIPを変更する場合は、
//    NVS設定、製造時書込み、または外部設定ファイル化を検討すること。
//  ・固定IPを使用する場合は、同一ネットワーク内でIPアドレスが重複しないようにすること。

//======================================================
//  Wi-Fi SSID設定
//======================================================
//  接続先アクセスポイントのSSIDを定義する。
//
//  本サンプルでは、HaLowカメラ用アクセスポイントとして
//  "halow_camera" に接続する想定である。
//
//  例：
//      AP側SSID : halow_camera
//      子機側   : 本WAH0070/NRC7394サンプルソフト
#define STR_SSID "halow_camera"

//======================================================
//  IPアドレス取得方式設定
//======================================================
//  Wi-Fi接続後のIPアドレス設定方式を指定する。
//
//  WIFI_STATIC_IP を指定した場合：
//      DHCPを使用せず、下記の NRC_STATIC_IP / NRC_NETMASK / NRC_GATEWAY を使用する。
//
//  DHCPを使用したい場合：
//      SDK側で定義されているDHCP用設定値へ変更する。
//      具体的な定義名は wifi_common/wifi_config.h を確認すること。
//
//  本サンプルでは、カメラ装置としてIPを固定し、
//  送信先サーバーやネットワーク確認を容易にするため、固定IPを使用する。
#define NRC_WIFI_IP_MODE    WIFI_STATIC_IP

//======================================================
//  固定IPアドレス設定
//======================================================
//  本デバイス自身に割り当てるIPv4アドレスを定義する。
//
//  本設定例：
//      デバイスIP : 192.168.200.21
//
//  注意：
//  ・同一LAN内で他機器と重複しない値にすること。
//  ・APまたはゲートウェイ側のネットワークアドレスと整合させること。
//  ・例では 192.168.200.0/24 のネットワークを想定している。
#define NRC_STATIC_IP "192.168.200.21"

//======================================================
//  サブネットマスク設定
//======================================================
//  本デバイスが所属するIPv4ネットワークのサブネットマスクを定義する。
//
//  本設定例：
//      255.255.255.0
//
//  上記設定では、ネットワーク範囲は概ね以下となる。
//      ネットワーク : 192.168.200.0/24
//      使用可能範囲 : 192.168.200.1 ～ 192.168.200.254
//
//  注意：
//  ・ゲートウェイ、送信先サーバー、AP側LAN設定と一致させること。
#define NRC_NETMASK "255.255.255.0"

//======================================================
//  デフォルトゲートウェイ設定
//======================================================
//  本デバイスが別ネットワークへ通信する際に使用するゲートウェイアドレスを定義する。
//
//  本設定例：
//      ゲートウェイ : 192.168.200.1
//
//  HaLow AP、LTEルーター、Raspberry Piゲートウェイなどを経由して
//  外部ネットワークへ画像データを送信する場合、この値が重要になる。
//
//  注意：
//  ・同一サブネット内のルーターまたはAPのLAN側IPアドレスを指定すること。
//  ・同一LAN内のサーバーだけに送信する構成では、通信経路によっては
//    ゲートウェイ未使用の場合もあるが、設定値としては正しく合わせておくこと。
#define NRC_GATEWAY "192.168.200.1"

#endif  // __WIFI_USER_CONFIG_H__
